const axios = require("axios");
const fs = require("fs-extra");
const path = require("path");
const g = require("fca-aryan-nix");

module.exports = {
config: {
name: "pixarai",
version: "1.1",
author: "NZR",
countDown: 5,
role: 0,
category: "AI",
shortDescription: {
en: "Generate AI images from text prompts"
},
longDescription: {
en: "Generate images using the Pixarai AI API."
},
guide: {
en: "{pn} <prompt>"
},
noPrefix: true
},

onStart: async function ({ message, args }) {
	const prompt = args.join(" ").trim();

	if (!prompt) {
		return message.reply(
			"❌ Please provide an image description.\n\n" +
			"Example: pixarai a cat floating in space"
		);
	}

	const apiUrl = "https://arychauhann.onrender.com/api/pixarai";

	let filePath;

	try {
		await message.reply("🎨 Generating your AI image. Please wait...");

		const response = await axios.get(apiUrl, {
			params: { prompt },
			timeout: 120000,
			headers: {
				"User-Agent": "Mozilla/5.0",
				"Accept": "application/json"
			}
		});

		const data = response.data;

		if (
			!data ||
			data.status !== true ||
			!data.result ||
			!data.result.url
		) {
			console.error("[PIXARAI API RESPONSE]", data);

			return message.reply(
				"❌ The image generator did not return an image.\n" +
				"Please try again with a different prompt."
			);
		}

		const imageUrl = data.result.url;

		if (
			typeof imageUrl !== "string" ||
			!/^https?:\/\//i.test(imageUrl)
		) {
			return message.reply(
				"❌ The API returned an invalid image URL."
			);
		}

		const cacheDir = path.join(__dirname, "cache");
		await fs.ensureDir(cacheDir);

		const fileName = `${Date.now()}_${String(data.result.id || "pixarai")
			.replace(/[^a-zA-Z0-9_-]/g, "")}.img`;

		filePath = path.join(cacheDir, fileName);

		const imageResponse = await axios.get(imageUrl, {
			responseType: "stream",
			timeout: 120000,
			maxRedirects: 5,
			validateStatus: status => status >= 200 && status < 300
		});

		const contentType = String(
			imageResponse.headers["content-type"] || ""
		).toLowerCase();

		if (!contentType.startsWith("image/")) {
			imageResponse.data.destroy();

			return message.reply(
				"❌ The image server returned an invalid file."
			);
		}

		await new Promise((resolve, reject) => {
			const output = fs.createWriteStream(filePath);

			imageResponse.data.pipe(output);

			output.on("finish", resolve);
			output.on("error", reject);
			imageResponse.data.on("error", reject);
		});

		const stats = await fs.stat(filePath);

		if (!stats.size) {
			throw new Error("The downloaded image file is empty.");
		}

		await new Promise((resolve, reject) => {
			message.reply(
				{
					body:
						"🎨 PIXARAI AI IMAGE\n\n" +
						`📝 Prompt: ${prompt}\n\n` +
						"♤ Generated by NZR",
					attachment: fs.createReadStream(filePath)
				},
				err => err ? reject(err) : resolve()
			);
		});
	} catch (error) {
		console.error(
			"[PIXARAI ERROR]",
			error.response?.data || error.message || error
		);

		return message.reply(
			"❌ Image generation failed.\n\n" +
			"Possible reasons:\n" +
			"• The Pixarai API is unavailable.\n" +
			"• The API response format has changed.\n" +
			"• The image server rejected the request.\n\n" +
			"Please try again later."
		);
	} finally {
		if (filePath) {
			await fs.remove(filePath).catch(() => {});
		}
	}
}

};

const w = new g.GoatWrapper(module.exports);
w.applyNoPrefix({ allowPrefix: false });
